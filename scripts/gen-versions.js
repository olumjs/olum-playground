const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");

function readVersion(pkg) {
  const pkgPath = path.join(root, "node_modules", pkg, "package.json");
  return JSON.parse(fs.readFileSync(pkgPath, "utf-8")).version;
}

const olumVersion = readVersion("olum");
const olumCompilerVersion = readVersion("olum-compiler");

const out = `// Auto-generated by scripts/gen-versions.js from node_modules — do not edit by hand.
export const OLUM_VERSION = "${olumVersion}";
export const OLUM_COMPILER_VERSION = "${olumCompilerVersion}";
`;

fs.writeFileSync(path.join(root, "src", "utils", "versions.js"), out);
console.log(`versions.js updated: olum ${olumVersion}, olum-compiler ${olumCompilerVersion}`);
